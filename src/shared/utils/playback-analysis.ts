import type { ContentPlayheadState, VideoElement } from '../messages';

import { formatPlaybackTime, getInterpolatedContentTime } from './content-playhead';

export const PLAYBACK_ANALYSIS_REASONING_VERSION = '1.0.0';
export const PLAYBACK_ANALYSIS_MAX_OBSERVATIONS = 120;

export interface PlaybackAnalysisCandidate {
  index: number;
  selected: boolean;
  duration: number;
  mediaTime: number;
  hasSource: boolean;
  visible: boolean;
  width: number;
  height: number;
  paused: boolean;
  seeking: boolean;
  buffering: boolean;
}

export interface PlaybackAnalysisObservation {
  elapsedMs: number;
  videoCount: number;
  candidates: PlaybackAnalysisCandidate[];
  selectedCandidateIndex?: number;
  contentTime?: number;
  contentDuration?: number;
  playing?: boolean;
  suspended?: boolean;
  confidence: 'high' | 'medium' | 'low' | 'unknown';
  interpretation: string;
}

export interface PlaybackAnalysisLedger {
  startedAtMs: number;
  lastRecordedAtMs: number;
  totalObservations: number;
  omittedObservations: number;
  observations: PlaybackAnalysisObservation[];
}

const MAX_CANDIDATES_PER_OBSERVATION = 8;
const MIN_SAMPLE_INTERVAL_MS = 5_000;
const SIGNIFICANT_TIME_CHANGE_SECONDS = 2;

export function recordPlaybackAnalysisObservation(
  ledger: PlaybackAnalysisLedger | undefined,
  videos: VideoElement[],
  previousPlayhead: ContentPlayheadState | undefined,
  nextPlayhead: ContentPlayheadState | undefined,
  observedAtMs: number,
): PlaybackAnalysisLedger {
  const nextLedger: PlaybackAnalysisLedger = ledger
    ? { ...ledger, observations: [...ledger.observations] }
    : {
        startedAtMs: observedAtMs,
        lastRecordedAtMs: observedAtMs,
        totalObservations: 0,
        omittedObservations: 0,
        observations: [],
      };
  nextLedger.totalObservations += 1;

  const lastObservation = nextLedger.observations[nextLedger.observations.length - 1];
  const selectedCandidateIndex = videos.findIndex(
    (video) => video.id === nextPlayhead?.videoId,
  );
  const candidateIndices = Array.from(
    { length: Math.min(videos.length, MAX_CANDIDATES_PER_OBSERVATION) },
    (_, index) => index,
  );
  if (
    selectedCandidateIndex >= MAX_CANDIDATES_PER_OBSERVATION &&
    candidateIndices.length === MAX_CANDIDATES_PER_OBSERVATION
  ) {
    candidateIndices[candidateIndices.length - 1] = selectedCandidateIndex;
  }
  const candidates = candidateIndices.map((index) => {
    const video = videos[index];
    return {
      index,
      selected: selectedCandidateIndex === index,
      duration: roundToTenths(video.duration),
      mediaTime: roundToTenths(video.currentTime),
      hasSource: video.hasSource,
      visible: video.isVisible,
      width: roundToInteger(video.width),
      height: roundToInteger(video.height),
      paused: video.paused,
      seeking: video.seeking ?? false,
      buffering: video.buffering ?? false,
    };
  });

  if (!shouldRecordObservation(
    lastObservation,
    candidates,
    videos.length,
    nextPlayhead,
    observedAtMs - nextLedger.lastRecordedAtMs,
  )) {
    return nextLedger;
  }

  const observation: PlaybackAnalysisObservation = {
    elapsedMs: Math.max(0, observedAtMs - nextLedger.startedAtMs),
    videoCount: videos.length,
    candidates,
    ...(selectedCandidateIndex >= 0 ? { selectedCandidateIndex } : {}),
    ...(nextPlayhead
      ? {
          contentTime: roundToTenths(nextPlayhead.currentTime),
          contentDuration: roundToTenths(nextPlayhead.duration),
          playing: nextPlayhead.playing,
          suspended: nextPlayhead.suspended,
        }
      : {}),
    confidence: nextPlayhead?.confidence ?? 'unknown',
    interpretation: explainPlayhead(previousPlayhead, nextPlayhead, selectedCandidateIndex),
  };

  nextLedger.lastRecordedAtMs = observedAtMs;
  nextLedger.observations.push(observation);
  if (nextLedger.observations.length > PLAYBACK_ANALYSIS_MAX_OBSERVATIONS) {
    nextLedger.observations.shift();
    nextLedger.omittedObservations += 1;
  }
  return nextLedger;
}

export function createPlaybackAnalysisReport(
  ledger: PlaybackAnalysisLedger | undefined,
  playhead: ContentPlayheadState | undefined,
  nowMs: number,
): string {
  const observations = ledger?.observations ?? [];
  const currentTime = getInterpolatedContentTime(playhead, nowMs);
  const latestObservation = observations[observations.length - 1];
  const playbackStatus = !playhead
    ? 'Unavailable'
    : playhead.suspended
      ? 'Suspended while the observed timeline is inconsistent'
      : playhead.playing
        ? 'Playing'
        : 'Paused or not advancing';

  const lines = [
    '# Playback analysis report',
    '',
    `Reasoning version: ${PLAYBACK_ANALYSIS_REASONING_VERSION}`,
    'Generated by a user-invoked local export. Times below are relative to the first recorded observation.',
    '',
    '## Summary',
    '',
    `- Content position: ${currentTime === undefined ? 'unavailable' : `${formatPlaybackTime(currentTime, true)} / ${formatPlaybackTime(playhead?.duration ?? 0, false)}`}`,
    `- Playback state: ${playbackStatus}`,
    `- Confidence: ${playhead?.confidence ?? 'unknown'}`,
    `- Recorded observations: ${ledger?.totalObservations ?? 0}; retained evidence points: ${observations.length}${ledger?.omittedObservations ? `; older points omitted from the bounded report: ${ledger.omittedObservations}` : ''}`,
    `- Latest interpretation: ${latestObservation?.interpretation ?? 'No video observations have been recorded for this tab yet.'}`,
    '',
    'The content position is a heuristic estimate from ordinary video-element behavior. This version does not classify ads, subtract ad time from an unchanged stitched timeline, or estimate ad-block/next-ad countdowns.',
    '',
    '## Evidence and interpretation',
    '',
  ];

  if (observations.length === 0) {
    lines.push('No video observations are available. Open the popup while the page is active and export again after video behavior has been observed.');
  } else {
    observations.forEach((observation, observationIndex) => {
      const selected = observation.selectedCandidateIndex === undefined
        ? 'none'
        : `video ${observation.selectedCandidateIndex + 1}`;
      const contentPosition = observation.contentTime === undefined
        ? 'unavailable'
        : `${formatPlaybackTime(observation.contentTime, true)} / ${formatPlaybackTime(observation.contentDuration ?? 0, false)}`;
      lines.push(
        `### ${formatElapsedTime(observation.elapsedMs)} — evidence point ${observationIndex + 1}`,
        '',
        `- Observed: ${observation.videoCount} video element(s); selected ${selected}; content-clock estimate ${contentPosition}; state ${describeState(observation)}; confidence ${observation.confidence}.`,
        `- Interpretation: ${observation.interpretation}`,
      );
      if (observation.candidates.length > 0) {
        lines.push('- Video observations:');
        observation.candidates.forEach((candidate) => {
          lines.push(
            `  - Video ${candidate.index + 1}${candidate.selected ? ' (selected)' : ''}: ${candidate.hasSource ? 'has source' : 'no source'}; media time ${formatPlaybackTime(candidate.mediaTime, true)} / duration ${formatPlaybackTime(candidate.duration, false)}; ${candidate.width}x${candidate.height}px; ${candidate.visible ? 'visible' : 'not visible'}; ${candidate.paused ? 'paused' : 'not paused'}; ${candidate.seeking ? 'seeking' : 'not seeking'}; ${candidate.buffering ? 'buffering' : 'not buffering'}.`,
          );
        });
      }
      lines.push('');
    });
  }

  lines.push(
    '## How the estimate is formed',
    '',
    '- Candidate video elements are ranked using source availability, duration, visibility, rendered area, and whether playback is active. No service or platform identity is used.',
    '- The selected element’s media time and duration anchor the estimate. A substantially shorter timeline can suspend the content clock; a much longer returning timeline can cause it to re-anchor. While playback is active, the popup interpolates between observations using the reported playback rate.',
    '- Confidence is qualitative, not a calibrated probability. The evidence points contain only bounded snapshots and decision summaries; uninteresting repeated updates are sampled rather than exported individually.',
    '- At most eight video candidates are summarized at each evidence point; the selected candidate is retained when it falls outside the first seven.',
    '',
    '## Limitations and privacy',
    '',
    '- A short first timeline may be an ad or short-form content; this implementation cannot reliably tell which.',
    '- Ads stitched into a timeline whose duration remains constant may still advance the displayed content position.',
    '- A seek, source replacement, unusual player transition, or a background service-worker restart can leave gaps or cause a re-anchoring error. Evidence is held in memory and is not durable.',
    '- This report excludes page titles and text, URLs, media element identifiers, network requests and response bodies, account information, and cookies. It is generated locally and is not transmitted automatically.',
    '',
  );

  return lines.join('\n');
}

function shouldRecordObservation(
  previous: PlaybackAnalysisObservation | undefined,
  candidates: PlaybackAnalysisCandidate[],
  videoCount: number,
  playhead: ContentPlayheadState | undefined,
  elapsedSincePreviousMs: number,
): boolean {
  if (!previous) return true;
  if (elapsedSincePreviousMs >= MIN_SAMPLE_INTERVAL_MS) return true;
  if (previous.videoCount !== videoCount) return true;
  if (previous.selectedCandidateIndex !== candidates.find((candidate) => candidate.selected)?.index) {
    return true;
  }
  if (
    previous.playing !== playhead?.playing ||
    previous.suspended !== playhead?.suspended ||
    previous.confidence !== (playhead?.confidence ?? 'unknown')
  ) {
    return true;
  }
  if (
    playhead &&
    previous.contentDuration !== roundToTenths(playhead.duration)
  ) {
    return true;
  }
  const selected = candidates.find((candidate) => candidate.selected);
  if (!selected && previous.candidates.length > 0) return true;
  return candidates.some((candidate) => {
    const previousCandidate = previous.candidates.find(
      (previousEntry) => previousEntry.index === candidate.index,
    );
    if (!previousCandidate) return true;
    return (
      candidate.paused !== previousCandidate.paused ||
      candidate.seeking !== previousCandidate.seeking ||
      candidate.buffering !== previousCandidate.buffering ||
      candidate.hasSource !== previousCandidate.hasSource ||
      candidate.visible !== previousCandidate.visible ||
      Math.abs(candidate.duration - previousCandidate.duration) > 5 ||
      Math.abs(candidate.width - previousCandidate.width) > 20 ||
      Math.abs(candidate.height - previousCandidate.height) > 20 ||
      Math.abs(candidate.mediaTime - previousCandidate.mediaTime) >= SIGNIFICANT_TIME_CHANGE_SECONDS
    );
  });
}

function explainPlayhead(
  previous: ContentPlayheadState | undefined,
  current: ContentPlayheadState | undefined,
  selectedCandidateIndex: number,
): string {
  if (!current) {
    return 'No eligible video candidate was available, so no content position could be estimated.';
  }
  if (!previous) {
    return 'Initialized from a candidate selected by generic video behavior (duration, visibility, rendered area, and playback activity). This does not establish whether the timeline contains advertisements.';
  }
  if (current.suspended) {
    return 'The selected media timeline changed substantially or became shorter than its established duration. The clock retained its prior content position instead of adopting the new media time; this is not proof that an advertisement is playing.';
  }
  if (previous.suspended && !current.suspended) {
    return 'A longer timeline returned after suspension, so the clock re-anchored to the observed media time. This is consistent with a timeline transition but does not identify its cause.';
  }
  if (selectedCandidateIndex < 0) {
    return 'No eligible video candidate is currently present, so the prior estimate was held and marked not advancing rather than inventing a new position.';
  }
  if (previous.videoId !== current.videoId) {
    return 'The chosen video candidate changed, so the estimate was anchored to that candidate’s observed media time. Candidate selection does not identify the service or prove content/ad identity.';
  }
  return 'The estimate follows the selected video’s observed media time and playback state; the popup interpolates between observations using playback rate. No ad classification is made.';
}

function describeState(observation: PlaybackAnalysisObservation): string {
  if (observation.suspended) return 'clock suspended';
  if (observation.playing) return 'playing';
  if (observation.contentTime === undefined) return 'unavailable';
  return 'paused or not advancing';
}

function formatElapsedTime(elapsedMs: number): string {
  return `${(elapsedMs / 1000).toFixed(1)}s`;
}

function roundToTenths(value: number): number {
  return Number.isFinite(value) ? Math.round(value * 10) / 10 : 0;
}

function roundToInteger(value: number): number {
  return Number.isFinite(value) ? Math.round(value) : 0;
}
